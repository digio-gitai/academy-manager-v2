GRADE_ORDER: list[str] = ["중1", "중2", "중3", "고1", "고2", "고3"]

UNCLASSIFIED = "미분류"


def _build_all_topic_options() -> list[str]:
    options: list[str] = [UNCLASSIFIED]
    for grade in GRADE_ORDER:
        for _major, minors in TOPIC_TREE.get(grade, []):
            for minor in minors:
                options.append(f"[{grade}] {minor}")
    return options


# 등록 화면 드롭다운·유사문제 매칭에서 쓰는 확정 태그 목록. "[학년] 소단원명" 형식.
ALL_TOPIC_OPTIONS: list[str] = _build_all_topic_options()


def match_topic_guess(raw_topic: str) -> str:
    """OCR/AI가 자유 텍스트로 추측한 단원명을 확정 태그로 최대한 매칭.

    정확히 일치하는 게 없으면, 소단원명에 raw_topic이 그대로 포함된 옵션이
    '단 하나'일 때만 그걸로 매칭합니다 (여러 개 걸리면 잘못 찍을 위험이 있어
    그냥 미분류로 남기고 사람이 고르게 함).
    """
    raw = (raw_topic or "").strip()
    if not raw or raw == UNCLASSIFIED:
        return UNCLASSIFIED
    if raw in ALL_TOPIC_OPTIONS:
        return raw

    candidates = [opt for opt in ALL_TOPIC_OPTIONS if raw in opt]
    if len(candidates) == 1:
        return candidates[0]
    return UNCLASSIFIED
